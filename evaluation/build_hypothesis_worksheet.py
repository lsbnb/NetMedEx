#!/usr/bin/env python3
"""Build a blinded hypothesis-rating worksheet for the hypothesis/two_hop_path stratum.

Extracts the real netmedex_hybrid_rag / traditional_rag answers already generated by the
formal-v1-gpt-5.6-terra run for every question_type in {hypothesis, two_hop_path}, strips
system identity, and assigns a randomized A/B label per question so a blinded rater cannot
infer which system produced which answer from row order.

Outputs:
  - <output-dir>/hypothesis_ratings_worksheet.csv : blinded, hand to the rater.
  - <output-dir>/hypothesis_ratings_key.csv        : hypothesis_id -> system mapping. Do not
    share with the blinded rater; used only to merge ratings back into hypothesis_ratings.csv.
"""

from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path

STRATUM_TYPES = {"hypothesis", "two_hop_path", "mechanism"}
# Q005 is phrased as a negative-control question ("Does X directly support a mechanistic link...")
# rather than a hypothesis-generation question -- scoring a deliberately cautious/hedged answer on
# "novelty" is a category error for this rubric, so it's excluded even though its question_type is
# "mechanism". See evaluation/formal_v2/relevance_guidelines.md's negative-control section for the
# same distinction applied to relevance grading.
EXCLUDE_IDS = {"Q005"}
SYSTEMS = ("netmedex_hybrid_rag", "traditional_rag")

WORKSHEET_FIELDS = [
    "question_id",
    "question_type",
    "domain",
    "question",
    "hypothesis_id",
    "answer_text",
    "rater_id",
    "novelty",
    "plausibility",
    "testability",
    "research_value",
    "notes",
]

KEY_FIELDS = ["hypothesis_id", "question_id", "system"]


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, fieldnames: list[str], rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def build(
    questions_path: Path,
    system_outputs_path: Path,
    output_dir: Path,
    seed: int,
) -> tuple[int, list[str], list[str]]:
    questions = {row["question_id"]: row for row in read_csv(questions_path)}
    stratum_ids = [
        qid
        for qid, row in questions.items()
        if row["question_type"] in STRATUM_TYPES and qid not in EXCLUDE_IDS
    ]
    if not stratum_ids:
        raise ValueError("No questions matched the hypothesis/mechanism stratum")

    outputs = read_csv(system_outputs_path)
    answers: dict[tuple[str, str], str] = {
        (row["question_id"], row["system"]): row["answer"]
        for row in outputs
        if row["system"] in SYSTEMS
    }

    missing = [
        (qid, system)
        for qid in stratum_ids
        for system in SYSTEMS
        if (qid, system) not in answers or not answers[(qid, system)].strip()
    ]
    if missing:
        raise ValueError(f"Missing/blank answers for: {missing}")

    # Preserve any already-assigned A/B mapping exactly -- questions already rated by AI raters
    # must keep the same hypothesis_id -> system mapping, or merging new ratings against a
    # regenerated key would silently mislabel which system a rated answer came from.
    key_path = output_dir / "hypothesis_ratings_key.csv"
    existing_by_qid: dict[str, dict[str, str]] = {}
    if key_path.exists():
        for row in read_csv(key_path):
            qid = row["question_id"]
            label = row["hypothesis_id"].rsplit("-", 1)[-1]
            existing_by_qid.setdefault(qid, {})[label] = row["system"]

    worksheet_rows: list[dict[str, str]] = []
    key_rows: list[dict[str, str]] = []
    new_qids: list[str] = []

    for qid in sorted(stratum_ids):
        q = questions[qid]
        if qid in existing_by_qid:
            assignment = existing_by_qid[qid]
        else:
            systems_order = list(SYSTEMS)
            # Per-question independent RNG (not a single shared generator consumed in
            # sorted-qid order) so adding new questions to the stratum never reshuffles the
            # A/B assignment already handed out for questions rated in an earlier pass.
            random.Random(f"{seed}:{qid}").shuffle(systems_order)
            assignment = dict(zip(("A", "B"), systems_order))
            new_qids.append(qid)

        for label, system in assignment.items():
            hypothesis_id = f"{qid}-{label}"
            worksheet_rows.append(
                {
                    "question_id": qid,
                    "question_type": q["question_type"],
                    "domain": q["domain"],
                    "question": q["question"],
                    "hypothesis_id": hypothesis_id,
                    "answer_text": answers[(qid, system)],
                    "rater_id": "",
                    "novelty": "",
                    "plausibility": "",
                    "testability": "",
                    "research_value": "",
                    "notes": "",
                }
            )
            key_rows.append(
                {"hypothesis_id": hypothesis_id, "question_id": qid, "system": system}
            )

    write_csv(output_dir / "hypothesis_ratings_worksheet.csv", WORKSHEET_FIELDS, worksheet_rows)
    write_csv(key_path, KEY_FIELDS, key_rows)

    if new_qids:
        new_rows = [row for row in worksheet_rows if row["question_id"] in new_qids]
        write_csv(output_dir / "hypothesis_ratings_worksheet_new.csv", WORKSHEET_FIELDS, new_rows)

    return len(worksheet_rows), sorted(stratum_ids), sorted(new_qids)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--questions", type=Path, default=Path("evaluation/formal/questions.csv")
    )
    parser.add_argument(
        "--system-outputs",
        type=Path,
        default=Path("evaluation/formal/runs/formal-v1-gpt-5.6-terra/system_outputs.csv"),
    )
    parser.add_argument("--output-dir", type=Path, default=Path("evaluation/formal"))
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Fixed seed so the A/B blinding assignment is reproducible.",
    )
    args = parser.parse_args()

    count, stratum_ids, new_qids = build(
        args.questions, args.system_outputs, args.output_dir, args.seed
    )
    print(f"Wrote {count} blinded rows for {len(stratum_ids)} questions: {stratum_ids}")
    print(f"Worksheet: {args.output_dir / 'hypothesis_ratings_worksheet.csv'}")
    print(f"Key (do not share with blinded rater): {args.output_dir / 'hypothesis_ratings_key.csv'}")
    if new_qids:
        print(f"New questions since the last key ({len(new_qids)}): {new_qids}")
        print(f"Delta worksheet for rating only the new questions: "
              f"{args.output_dir / 'hypothesis_ratings_worksheet_new.csv'}")
    else:
        print("No new questions since the last key -- nothing to re-rate.")


if __name__ == "__main__":
    main()
